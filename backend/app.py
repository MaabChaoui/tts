"""
One-word replacement tool (local web interface).

Upload or record a short clip, transcribe it, pick a word, type its
replacement, and generate the edited clip with either method:
  - neural edit: F5-TTS infilling with SILMA TTS weights (Arabic, English)
  - splice:      XTTS v2 zero-shot cloning, new word cut and pasted (runs word_swap.py in .venv)

Run from backend/:
    .venv-f5/bin/python app.py
then open http://127.0.0.1:7861. Local only: no public link is created.
Every run is saved under outputs/word_swap/<run>-app/ (gitignored).
"""

import json
import os
import subprocess
import sys
import threading

import gradio as gr
import soundfile as sf

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import swaplib as sl
from neural_edit import F5Editor, edit_word

MAX_CLIP_S = 30
PORT = 7861
NEURAL = "Neural edit (F5-TTS + SILMA)"
SPLICE = "Splice (XTTS v2)"
LANGS = {"Arabic": "ar", "English": "en", "French": "fr", "Spanish": "es", "Russian": "ru"}
NEURAL_LANGS = {"ar", "en"}
XTTS_PY = os.path.join(sl.HERE, ".venv", "bin", "python")

_models = {}
_gpu = threading.Lock()


def transcriber():
    if "tr" not in _models:
        _models["tr"] = sl.Transcriber("cuda")
    return _models["tr"]


def editor():
    if "f5" not in _models:
        _models["f5"] = F5Editor()
    return _models["f5"]


def on_upload(path):
    if not path:
        return None, "Upload or record a clip.", gr.update(choices=[], value=None), ""
    audio = sl.load_any(path)
    dur = len(audio) / sl.SR
    if dur > MAX_CLIP_S:
        raise gr.Error(f"The clip is {dur:.1f} s long. Keep it under {MAX_CLIP_S} s.")
    if dur < 2:
        raise gr.Error("The clip is shorter than 2 s; the voice cannot be cloned from that.")
    state = {"audio": audio, "name": os.path.basename(path), "words": []}
    return state, f"Loaded {dur:.1f} s. Now click **Transcribe**.", gr.update(choices=[], value=None), ""


def on_transcribe(state, lang_name):
    if not state:
        raise gr.Error("Upload or record a clip first.")
    lang = LANGS[lang_name]
    with _gpu:
        words = transcriber().words(state["audio"], lang)
    if not words:
        raise gr.Error("Whisper found no words in this clip.")
    state = {**state, "words": words, "lang": lang}
    choices = [(f"{w['word']}  ·  {w['start']:.1f}s", i) for i, w in enumerate(words)]
    rtl = ["rtl"] if lang == "ar" else []
    return (state, gr.update(choices=choices, value=None, elem_classes=rtl),
            gr.update(value=" ".join(w["word"] for w in words), rtl=bool(rtl)),
            f"{len(words)} words. Click the word to replace.")


def on_edit_inputs(state, k, new_word):
    if not state or not state.get("words") or k is None:
        return gr.update()
    words = [w["word"] for w in state["words"]]
    if new_word and new_word.strip():
        words[k] = new_word.strip()
    return gr.update(value=" ".join(words))


def run_generate(state, k, new_word, text, method, seed, context=1, new_dur=0):
    if not state or not state.get("words"):
        raise gr.Error("Transcribe the clip first.")
    if k is None:
        raise gr.Error("Click the word to replace.")
    new_word = (new_word or "").strip()
    if not new_word:
        raise gr.Error("Type the new word.")
    lang, words, audio = state["lang"], state["words"], state["audio"]
    seed = int(seed)
    out = sl.new_run_dir("app")
    sf.write(os.path.join(out, "clip.wav"), audio, sl.SR)

    with _gpu:
        if method == NEURAL:
            if lang not in NEURAL_LANGS:
                raise gr.Error("The neural editor (SILMA) only supports Arabic and English. Use Splice.")
            record = edit_word(editor(), audio, words, k, new_word, out, text, seed, transcriber(), lang,
                               float(new_dur) or None, int(context))
            third, third_label = os.path.join(out, "regen.wav"), "Whole clip regenerated by the vocoder"
        else:
            with open(os.path.join(out, "words.json"), "w") as f:
                json.dump(words, f, ensure_ascii=False)
            cmd = [XTTS_PY, os.path.join(sl.HERE, "word_swap.py"), "edit", "--clip", os.path.join(out, "clip.wav"),
                   "--words-json", os.path.join(out, "words.json"), "--word-index", str(k), "--new-word", new_word,
                   "--text", text, "--lang", lang, "--seed", str(seed), "--out", out, "--whisper-device", "cpu"]
            proc = subprocess.run(cmd, capture_output=True, text=True, cwd=sl.HERE)
            lines = [ln for ln in proc.stdout.splitlines() if ln.startswith("RESULT ")]
            if not lines:
                raise gr.Error("XTTS helper failed: " + (proc.stderr.strip().splitlines() or ["no output"])[-1])
            result = json.loads(lines[-1][len("RESULT "):])
            if not result["ok"]:
                raise gr.Error(result["error"])
            record = result["record"]
            fake, _ = sf.read(os.path.join(out, "fake.wav"), dtype="float32")
            record["whisper_hears"] = {"fake": " ".join(w["word"] for w in transcriber().words(fake, lang))}
            sl.write_record(out, record)
            third, third_label = os.path.join(out, "synth_full.wav"), "Whole sentence cloned by XTTS"

    record = {"clip": state["name"], **record}
    sl.write_record(out, record)
    heard = (record.get("whisper_hears") or {}).get("fake", "")
    summary = (f"**{words[k]['word']} → {new_word}** · {method} · seed {seed} · {record['seconds']} s\n\n"
               f"Whisper hears the fake as: {heard}\n\nSaved in `{os.path.relpath(out, sl.HERE)}`")
    return (os.path.join(out, "fake.wav"), gr.update(value=third, label=third_label),
            os.path.join(out, "splice.png"), summary, record)


def on_retry(state, k, new_word, text, method, seed, context, new_dur):
    seed = int(seed) + 1
    return (seed, *run_generate(state, k, new_word, text, method, seed, context, new_dur))


CSS = """
.rtl .wrap { direction: rtl; }
#title h1 { font-weight: 400; margin-bottom: 0; }
footer { display: none !important; }
"""

with gr.Blocks(title="Word Swap", css=CSS, theme=gr.themes.Base(primary_hue="orange", neutral_hue="stone")) as demo:
    gr.Markdown("# Change one word\nPretrained models, local only. Real voices: research use, do not share outputs.",
                elem_id="title")
    state = gr.State(None)
    with gr.Row():
        with gr.Column(scale=1):
            clip = gr.Audio(label="1 · Clip (under 30 s)", sources=["upload", "microphone"], type="filepath")
            lang = gr.Dropdown(list(LANGS), value="Arabic", label="Language")
            status = gr.Markdown("Upload or record a clip.")
            transcribe_btn = gr.Button("2 · Transcribe")
        with gr.Column(scale=2):
            word = gr.Radio(choices=[], label="3 · Word to replace", type="value")
            new_word = gr.Textbox(label="New word")
            text = gr.Textbox(label="Sentence given to the model (edit if needed, e.g. write numbers as words)",
                              lines=2)
            with gr.Row():
                method = gr.Radio([NEURAL, SPLICE], value=NEURAL, label="Method")
                seed = gr.Number(value=0, precision=0, label="Seed")
            with gr.Row():
                context = gr.Slider(0, 2, value=1, step=1, label="Neural edit: also regenerate this many words on each side",
                                    info="1 helps with fast or dialectal speech; neighbours may change slightly")
                new_dur = gr.Number(value=0, label="Neural edit: length of the new word in seconds (0 = automatic)")
            with gr.Row():
                generate_btn = gr.Button("4 · Generate", variant="primary")
                retry_btn = gr.Button("Try another seed")
    with gr.Row():
        fake = gr.Audio(label="Fake: one word replaced", type="filepath", interactive=False)
        third = gr.Audio(label="Second output", type="filepath", interactive=False)
    spec = gr.Image(label="Spectrogram around the edit (top: original, bottom: fake)", type="filepath",
                    interactive=False)
    summary = gr.Markdown()
    with gr.Accordion("Run record", open=False):
        record = gr.JSON()

    clip.change(on_upload, [clip], [state, status, word, text])
    transcribe_btn.click(on_transcribe, [state, lang], [state, word, text, status])
    word.change(on_edit_inputs, [state, word, new_word], [text])
    new_word.change(on_edit_inputs, [state, word, new_word], [text])
    outputs = [fake, third, spec, summary, record]
    inputs = [state, word, new_word, text, method, seed, context, new_dur]
    generate_btn.click(run_generate, inputs, outputs)
    retry_btn.click(on_retry, inputs, [seed, *outputs])

if __name__ == "__main__":
    demo.queue(default_concurrency_limit=1).launch(server_name="127.0.0.1", server_port=PORT, share=False)
